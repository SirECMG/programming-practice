main(Args) ->

    Ords = [81, 64, 75, 66, 70, 93, 73, 72, 1, 92, 109, 2, 84, 109, 66, 75, 70, 90, 2, 92, 79],

    Key = 16#32,

    Output = [ N bxor Key || N <- Ords],

    io:format("Flag: ~p~n", [Output]),
    erlang:halt(0).

